// 목록 카드용 주소 축약.
//
// 카드에서 주소가 잘리면(375px 기준 실측: 325px 주소가 226px만 보임) 정작 보호자가
// 가장 먼저 보는 "어느 동네인가"를 알 수 없다. 그런데 잘리는 글자의 상당수는
// "서울특별시"·"경상남도" 같은 시/도 정식 명칭이라, 이걸 줄이면 대부분 한 줄에 들어간다.
//
// 구/군/동은 절대 건드리지 않는다 — 그게 실제로 위치를 판단하는 정보다.
const SIDO_SHORT: [RegExp, string][] = [
  [/^서울특별시/, "서울"],
  [/^부산광역시/, "부산"],
  [/^대구광역시/, "대구"],
  [/^인천광역시/, "인천"],
  [/^광주광역시/, "광주"],
  [/^대전광역시/, "대전"],
  [/^울산광역시/, "울산"],
  [/^세종특별자치시/, "세종"],
  [/^경기도/, "경기"],
  [/^강원특별자치도|^강원도/, "강원"],
  [/^충청북도/, "충북"],
  [/^충청남도/, "충남"],
  [/^전북특별자치도|^전라북도/, "전북"],
  [/^전남광주통합특별시|^전라남도/, "전남"],
  [/^경상북도/, "경북"],
  [/^경상남도/, "경남"],
  [/^제주특별자치도/, "제주"],
];

export function shortAddress(address: string): string {
  for (const [pattern, short] of SIDO_SHORT) {
    if (pattern.test(address)) return address.replace(pattern, short);
  }
  return address;
}
