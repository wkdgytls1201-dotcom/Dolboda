/** 슬러그로 품목을 찾는다 — 상세 페이지 params 해석용 */
export function findEquipmentBySlug(slug: string): (EquipmentItem & { kind: "구입" | "대여" }) | undefined {
  const purchase = PURCHASE_ITEMS.find((i) => i.slug === slug);
  if (purchase) return { ...purchase, kind: "구입" };
  const rental = RENTAL_ITEMS.find((i) => i.slug === slug);
  if (rental) return { ...rental, kind: "대여" };
  return undefined;
}

