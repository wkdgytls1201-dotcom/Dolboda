/** 화면·메타데이터에 함께 표기할 기준 연도 — 숫자만 있고 기준이 없으면 신뢰가 안 생긴다 */
export const BASE_YEAR = 2026;

/** 올해가 며칠 남았는지 — "쓰지 않으면 소멸한다"는 사실을 막연한 경고가 아니라
 * 실제 숫자로 보여준다(과장 없이, KST 기준). */
export function daysLeftInYear(): number {
  const now = new Date();
  const kstNow = new Date(now.toLocaleString("en-US", { timeZone: "Asia/Seoul" }));
  const endOfYear = new Date(kstNow.getFullYear(), 11, 31, 23, 59, 59);
  return Math.max(0, Math.ceil((endOfYear.getTime() - kstNow.getTime()) / 86400000));
}

